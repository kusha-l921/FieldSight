"""
Labelme JSON to Binary Mask Converter for FieldSight-Lite Evaluation.

Converts polygon / rectangle / shape annotations in Labelme JSON files into
single-channel 8-bit binary PNG masks:
- 0: Background / Healthy Tissue
- 255: Lesion (or Leaf if specifically designated)

Usage:
    python experiments/convert_labelme_to_masks.py \
        --images-dir data/evaluation/images \
        --output-masks-dir data/evaluation/masks \
        --lesion-labels lesion blight spot necrosis chlorosis
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import sys
from typing import List, Tuple
import cv2
import numpy as np


def labelme_json_to_mask(
    json_path: str,
    target_shape: Tuple[int, int] = None,
    lesion_labels: List[str] = None
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Parses a single Labelme JSON file and generates binary masks for leaf and lesion.

    Args:
        json_path: Path to .json file generated by Labelme.
        target_shape: (height, width) tuple. If None, derived from JSON image size.
        lesion_labels: List of label strings considered as lesion (case-insensitive).

    Returns:
        (leaf_mask, lesion_mask) where:
            leaf_mask: uint8 array (255 inside leaf, 0 background)
            lesion_mask: uint8 array (255 inside lesion, 0 elsewhere)
    """
    if lesion_labels is None:
        lesion_labels = ["lesion", "blight", "early_blight", "spot", "necrosis", "chlorosis", "disease"]
    lesion_labels_lower = [l.lower() for l in lesion_labels]

    with open(json_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    img_h = data.get("imageHeight")
    img_w = data.get("imageWidth")

    if target_shape is not None:
        h, w = target_shape
    elif img_h is not None and img_w is not None:
        h, w = int(img_h), int(img_w)
    else:
        raise ValueError(f"Image dimensions not specified in {json_path}")

    leaf_mask = np.zeros((h, w), dtype=np.uint8)
    lesion_mask = np.zeros((h, w), dtype=np.uint8)

    has_explicit_leaf_label = False
    shapes = data.get("shapes", [])

    for shape in shapes:
        label = shape.get("label", "").strip().lower()
        points = np.array(shape.get("points", []), dtype=np.int32)
        shape_type = shape.get("shape_type", "polygon")

        if len(points) == 0:
            continue

        temp_mask = np.zeros((h, w), dtype=np.uint8)
        if shape_type == "polygon":
            cv2.fillPoly(temp_mask, [points], 255)
        elif shape_type == "rectangle":
            if len(points) >= 2:
                pt1 = (int(min(points[0][0], points[1][0])), int(min(points[0][1], points[1][1])))
                pt2 = (int(max(points[0][0], points[1][0])), int(max(points[0][1], points[1][1])))
                cv2.rectangle(temp_mask, pt1, pt2, 255, -1)
        elif shape_type == "circle":
            if len(points) >= 2:
                center = (int(points[0][0]), int(points[0][1]))
                radius = int(np.linalg.norm(points[0] - points[1]))
                cv2.circle(temp_mask, center, radius, 255, -1)
        else:
            cv2.fillPoly(temp_mask, [points], 255)

        if label in ["leaf", "blade", "foliage", "plant"]:
            leaf_mask = cv2.bitwise_or(leaf_mask, temp_mask)
            has_explicit_leaf_label = True
        elif any(l in label for l in lesion_labels_lower) or label not in ["background", "bg"]:
            lesion_mask = cv2.bitwise_or(lesion_mask, temp_mask)

    if not has_explicit_leaf_label:
        img_name = data.get("imagePath", "")
        img_full_path = os.path.join(os.path.dirname(json_path), img_name)
        if os.path.exists(img_full_path):
            img_bgr = cv2.imread(img_full_path)
            if img_bgr is not None:
                from src.leaf_segmentation import LeafSegmenter
                seg = LeafSegmenter()
                l_mask, l_area, is_valid = seg.segment_leaf(img_bgr)
                if is_valid and l_area > 0:
                    leaf_mask = l_mask
        if np.count_nonzero(leaf_mask) == 0:
            # Fallback only if segmentation totally failed
            leaf_mask = np.ones((h, w), dtype=np.uint8) * 255

    return leaf_mask, lesion_mask


def batch_convert(
    images_dir: str,
    output_masks_dir: str,
    lesion_labels: List[str] = None
) -> int:
    """
    Batch converts all JSON files found in images_dir into binary masks.
    """
    os.makedirs(output_masks_dir, exist_ok=True)
    json_files = glob.glob(os.path.join(images_dir, "*.json"))
    
    if not json_files:
        print(f"No .json files found in {images_dir}")
        return 0

    print(f"Found {len(json_files)} annotation files in {images_dir}...")
    converted_count = 0

    for jpath in json_files:
        base_name = os.path.splitext(os.path.basename(jpath))[0]
        img_candidates = glob.glob(os.path.join(images_dir, f"{base_name}.*"))
        target_shape = None
        for cand in img_candidates:
            if not cand.lower().endswith(".json"):
                img = cv2.imread(cand)
                if img is not None:
                    target_shape = (img.shape[0], img.shape[1])
                    break

        try:
            leaf_mask, lesion_mask = labelme_json_to_mask(jpath, target_shape=target_shape, lesion_labels=lesion_labels)
            
            lesion_out_path = os.path.join(output_masks_dir, f"{base_name}_lesion_mask.png")
            leaf_out_path = os.path.join(output_masks_dir, f"{base_name}_leaf_mask.png")
            
            cv2.imwrite(lesion_out_path, lesion_mask)
            cv2.imwrite(leaf_out_path, leaf_mask)
            converted_count += 1
            print(f"  [✓] Converted {base_name} -> {os.path.basename(lesion_out_path)}")
        except Exception as e:
            print(f"  [✗] Error processing {jpath}: {e}")

    print(f"\nConversion complete! {converted_count}/{len(json_files)} masks written to {output_masks_dir}")
    return converted_count


def main():
    parser = argparse.ArgumentParser(description="Convert Labelme JSON annotations to binary PNG masks")
    parser.add_argument("--images-dir", "-i", default="data/evaluation/images", help="Directory containing images and JSONs")
    parser.add_argument("--output-masks-dir", "-o", default="data/evaluation/masks", help="Directory to output binary masks")
    parser.add_argument("--lesion-labels", nargs="+", default=["lesion", "blight", "spot", "necrosis", "chlorosis"], help="Labels to treat as lesions")
    args = parser.parse_args()

    batch_convert(
        images_dir=args.images_dir,
        output_masks_dir=args.output_masks_dir,
        lesion_labels=args.lesion_labels
    )


if __name__ == "__main__":
    main()
